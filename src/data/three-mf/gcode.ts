export interface GcodeFallbackData {
  predictionSeconds: number | null
  totalWeightCentigrams: number | null
  filamentCentigrams: number[]
  generatedBy?: string
}

const DURATION_PATTERN =
  /^(?:(\d+)\s*d)?\s*(?:(\d+)\s*h)?\s*(?:(\d+)\s*m)?\s*(?:(\d+(?:\.\d+)?)\s*s)?$/i

export function parseDurationToSeconds(value: string): number | null {
  const match = DURATION_PATTERN.exec(value.trim())
  if (!match) return null
  const [, days, hours, minutes, seconds] = match
  if (!days && !hours && !minutes && !seconds) return null
  const total =
    Number(days ?? 0) * 86_400 +
    Number(hours ?? 0) * 3_600 +
    Number(minutes ?? 0) * 60 +
    Number(seconds ?? 0)
  if (!Number.isFinite(total) || total < 0 || !Number.isSafeInteger(Math.round(total))) {
    return null
  }
  return Math.round(total)
}

function parseGrams(value: string): number | null {
  const grams = Number.parseFloat(value.trim())
  if (!Number.isFinite(grams) || grams < 0) return null
  const centigrams = Math.round(grams * 100)
  return Number.isSafeInteger(centigrams) ? centigrams : null
}

function parseGramList(value: string): number[] {
  return value
    .split(',')
    .map((part) => parseGrams(part))
    .filter((grams): grams is number => grams !== null)
}

function lastMatch(source: string, pattern: RegExp): string | undefined {
  const flags = pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`
  const matches = [...source.matchAll(new RegExp(pattern.source, flags))]
  const last = matches.at(-1)
  return last?.[1]?.trim()
}

export function parseGcodeFallback(text: string): GcodeFallbackData {
  const head = text.length > 64 * 1024 ? text.slice(0, 64 * 1024) : text
  const tail = text.length > 512 * 1024 ? text.slice(-512 * 1024) : text

  const generatedBy = lastMatch(head, /^;\s*generated by\s+(.+?)\s+on\s+\d{4}-\d{2}-\d{2}/im)
  const predictionText =
    lastMatch(tail, /^;\s*estimated printing time \(normal mode\)\s*=\s*(.+)$/im) ??
    lastMatch(tail, /^;\s*estimated printing time\s*=\s*(.+)$/im)
  const predictionSeconds = predictionText ? parseDurationToSeconds(predictionText) : null

  const filamentMatches = [...tail.matchAll(/^;\s*filament used \[g\]\s*=\s*(.+)$/gim)]
  const filamentCentigrams = filamentMatches.flatMap((match) =>
    match[1] ? parseGramList(match[1]) : [],
  )
  const totalText = lastMatch(tail, /^;\s*total filament used \[g\]\s*=\s*(.+)$/im)
  const totalWeightCentigrams = totalText ? parseGrams(totalText) : null

  return {
    predictionSeconds,
    totalWeightCentigrams,
    filamentCentigrams,
    generatedBy,
  }
}
